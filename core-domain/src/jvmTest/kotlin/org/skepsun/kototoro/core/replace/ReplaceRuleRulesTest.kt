package org.skepsun.kototoro.core.replace

import kotlinx.coroutines.test.runTest
import org.junit.jupiter.api.Assertions.assertEquals
import org.junit.jupiter.api.Assertions.assertFalse
import org.junit.jupiter.api.Assertions.assertTrue
import org.junit.jupiter.api.Test

class ReplaceRuleRulesTest {

    @Test
    fun `normalize keeps unique ids and gives the rest fresh ones above now`() {
        val rules = listOf(
            ReplaceRule(id = 7L),
            ReplaceRule(id = 7L),
            ReplaceRule(id = 0L),
        )

        val normalized = normalizeReplaceRuleIds(rules, now = 100L)

        assertEquals(listOf(7L, 101L, 102L), normalized.map { it.id })
    }

    @Test
    fun `normalize pushes autogenerated ids past the stored maximum`() {
        val normalized = normalizeReplaceRuleIds(listOf(ReplaceRule(id = 5_000L), ReplaceRule(id = 0L)), now = 100L)

        assertEquals(listOf(5_000L, 5_001L), normalized.map { it.id })
    }

    @Test
    fun `import replaces a stored rule with the same id and appends the rest`() {
        val existing = listOf(ReplaceRule(id = 1L, pattern = "old"), ReplaceRule(id = 2L, pattern = "kept"))
        val imported = listOf(ReplaceRule(id = 1L, pattern = "new"), ReplaceRule(id = 0L, pattern = "added"),
            ReplaceRule(id = 0L, pattern = " "))

        val merge = mergeImportedReplaceRules(existing, imported, now = 500L)

        assertEquals(2, merge.importedCount)
        assertEquals(listOf("new", "kept", "added"), merge.rules.map { it.pattern })
        assertEquals(501L, merge.rules.last().id)
    }

    @Test
    fun `book filter keeps the rules that reach this book and drops invalid ones`() {
        val rules = listOf(
            ReplaceRule(id = 1L, pattern = "a", scopeFilter = "Some Book"),
            ReplaceRule(id = 2L, pattern = "b", scopeFilter = "Another"),
            ReplaceRule(id = 3L, pattern = "(", isRegex = true),
            ReplaceRule(id = 4L, pattern = "c", scopeTitle = false, scopeContent = false),
            ReplaceRule(id = 5L, pattern = "d", excludeScope = "Some Book"),
        )

        val filtered = filterReplaceRulesForBook(rules, scopeName = "Some Book", origin = "source-a")

        assertEquals(listOf(1L), filtered.map { it.id })
    }

    @Test
    fun `apply runs the rules in order and skips one that cannot compile`() = runTest {
        val applied = applyReplaceRules(
            text = "ad\nkeep\nad",
            rules = listOf(
                ReplaceRule(id = 1L, name = "drop ads", pattern = "ad\\n?", replacement = ""),
                // Android's `apply()` swallows an uncompilable pattern, so an invalid rule is a no-op, not a failure.
                ReplaceRule(id = 2L, name = "broken", pattern = "(", replacement = "x"),
            ),
        )

        assertEquals("keep\n", applied.text)
        assertTrue(applied.failedRuleNames.isEmpty())
    }

    @Test
    fun `apply skips disabled rules and the per-session disabled ids`() = runTest {
        val applied = applyReplaceRules(
            text = "abc",
            rules = listOf(
                ReplaceRule(id = 1L, pattern = "a", replacement = "1", isEnabled = false),
                ReplaceRule(id = 2L, pattern = "b", replacement = "2"),
            ),
            disabledIds = setOf(2L),
        )

        assertEquals("abc", applied.text)
        assertTrue(applied.failedRuleNames.isEmpty())
    }

    @Test
    fun `a plain text rule replaces literally`() = runTest {
        val applied = applyReplaceRules(
            text = "a.c",
            rules = listOf(ReplaceRule(id = 1L, pattern = ".", replacement = "-", isRegex = false)),
        )

        assertEquals("a-c", applied.text)
        assertFalse(applied.text.contains('.'))
    }
}
