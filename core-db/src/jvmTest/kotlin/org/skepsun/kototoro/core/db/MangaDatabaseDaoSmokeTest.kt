package org.skepsun.kototoro.core.db

import androidx.room.Room
import androidx.sqlite.driver.bundled.BundledSQLiteDriver
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.flow.first
import kotlinx.coroutines.runBlocking
import org.junit.jupiter.api.Assertions.assertEquals
import org.junit.jupiter.api.Assertions.assertFalse
import org.junit.jupiter.api.Assertions.assertTrue
import org.junit.jupiter.api.Test
import org.skepsun.kototoro.core.db.entity.MangaSourceEntity
import org.skepsun.kototoro.core.db.entity.MangaEntity
import org.skepsun.kototoro.explore.data.SourcesSortOrder
import org.skepsun.kototoro.tracker.data.TrackEntity
import org.skepsun.kototoro.tracker.data.TrackLogEntity
import org.skepsun.kototoro.suggestions.data.SuggestionEntity

/**
 * The real Kototoro schema and DAOs, generated by Room KMP, running on the bundled SQLite driver (the same driver
 * family iOS uses). Covers the paths that changed when the schema moved to commonMain: @RawQuery -> RoomRawQuery
 * (suspend and Flow), @Transaction open methods, @Upsert and @Insert(IGNORE).
 */
class MangaDatabaseDaoSmokeTest {

    @Test
    fun `query hints contain a title once when multiple sources suggest the same work`() = runBlocking {
        val db = newDb()
        try {
            val title = "Natsu Inaka Megane Shimai"
            for (id in 1L..2L) {
                db.getMangaDao().upsert(MangaEntity(
                    id = id, title = title, altTitles = null, url = "$id", publicUrl = "https://example.org/$id",
                    rating = 0f, isNsfw = false, contentRating = null, coverUrl = "", largeCoverUrl = null,
                    state = null, authors = null, source = "SOURCE_$id",
                ))
                db.getSuggestionDao().insert(SuggestionEntity(id, 1f, 1L))
            }

            assertEquals(listOf(title), db.getSuggestionDao().getTitles("na%"))
            assertTrue(db.getSuggestionDao().getTitles("naruto%").isEmpty())
        } finally {
            db.close()
        }
    }

    @Test
    fun `viewing a reminder clears unseen count while retaining pending chapters and discovery time`() = runBlocking {
        val db = newDb()
        try {
            db.getMangaDao().upsert(MangaEntity(
                id = 1, title = "Work", altTitles = null, url = "1", publicUrl = "https://example.org/1",
                rating = 0f, isNsfw = false, contentRating = null, coverUrl = "", largeCoverUrl = null,
                state = null, authors = null, source = "TEST",
            ))
            val tracks = db.getTracksDao()
            tracks.upsert(TrackEntity(1, 32, 2, 200, 999, TrackEntity.RESULT_HAS_UPDATE, null))
            assertEquals(1, tracks.observeUnreadWorkCount().first())
            db.getTrackLogsDao().ensureUnreadUpdateLogs()
            val event = db.getTrackLogsDao().dump().single()
            assertEquals(200, event.createdAt, "publication dates cannot date a discovery event")
            db.getTrackLogsDao().markAsRead(event.id)
            assertEquals(0, tracks.observeUnreadWorkCount().first())
            assertEquals(2, tracks.find(1)!!.newChapters)
            assertEquals(1, db.getTrackLogsDao().count())
        } finally { db.close() }
    }

    @Test
    fun `restoring a missing track uses the latest batch instead of summing overlapping history`() = runBlocking {
        val db = newDb()
        try {
            db.getMangaDao().upsert(MangaEntity(
                id = 1, title = "Work", altTitles = null, url = "1", publicUrl = "https://example.org/1",
                rating = 0f, isNsfw = false, contentRating = null, coverUrl = "", largeCoverUrl = null,
                state = null, authors = null, source = "TEST",
            ))
            val logs = db.getTrackLogsDao()
            repeat(9) { index ->
                logs.insert(TrackLogEntity(mangaId = 1, chapters = (1..32).joinToString("\n") { "Chapter $it" },
                    createdAt = index + 1L, isUnread = true))
            }
            logs.insert(TrackLogEntity(mangaId = 1, chapters = (1..16).joinToString("\n") { "Chapter $it" },
                createdAt = 10, isUnread = true))
            val tracks = db.getTracksDao()
            tracks.insertTracksFromUnreadLogs()
            assertEquals(16, tracks.find(1)!!.newChapters)
            assertEquals(10, tracks.find(1)!!.lastCheckTime)
            assertEquals(0, tracks.find(1)!!.lastChapterDate, "a discovery date is not a publication date")
            repeat(3) { tracks.insertTracksFromUnreadLogs() }
            assertEquals(16, tracks.find(1)!!.newChapters)
            assertEquals(10, logs.count(), "restoring a counter must retain history")

            tracks.upsert(TrackEntity(1, 32, 2, 20, 5, TrackEntity.RESULT_HAS_UPDATE, null))
            tracks.insertTracksFromUnreadLogs()
            assertEquals(2, tracks.find(1)!!.newChapters, "existing counters are authoritative")
            tracks.clearCounter(1)
            tracks.insertTracksFromUnreadLogs()
            assertEquals(0, tracks.find(1)!!.newChapters, "historical unread logs must not resurrect a cleared counter")
        } finally {
            db.close()
        }
    }

    private fun newDb(): MangaDatabase = Room.inMemoryDatabaseBuilder<MangaDatabase>()
        .setDriver(BundledSQLiteDriver())
        .setQueryCoroutineContext(Dispatchers.IO)
        .build()

    private fun source(name: String, enabled: Boolean, sortKey: Int) = MangaSourceEntity(
        source = name, isEnabled = enabled, sortKey = sortKey, addedIn = 1, lastUsedAt = 0L, isPinned = false, cfState = 0,
    )

    @Test
    fun `RoomRawQuery suspend and Flow paths return filtered and ordered rows`() = runBlocking {
        val db = newDb()
        try {
            val dao = db.getSourcesDao()
            dao.insertIfAbsent(listOf(source("c", true, 3), source("a", true, 2), source("b", false, 1)))

            assertEquals(listOf("a", "c"), dao.findAll(enabledOnly = true, order = SourcesSortOrder.ALPHABETIC).map { it.source })
            assertEquals(
                listOf("b", "a", "c"),
                dao.observeAll(enabledOnly = false, order = SourcesSortOrder.MANUAL).first().map { it.source },
            )
        } finally {
            db.close()
        }
    }

    @Test
    fun `Transaction upsert and insert-ignore behave like the Android schema`() = runBlocking {
        val db = newDb()
        try {
            val dao = db.getSourcesDao()
            dao.insertIfAbsent(listOf(source("x", true, 1)))
            dao.insertIfAbsent(listOf(source("x", false, 99))) // IGNORE: the first row must survive
            assertEquals(1, dao.find("x")!!.sortKey)
            assertTrue(dao.find("x")!!.isEnabled)

            dao.setPinned("x", true, appVersionCode = 42) // @Transaction open suspend fun
            assertEquals(listOf("x"), dao.findAllPinned().map { it.source })

            dao.upsert(source("x", false, 7))
            val row = dao.find("x")!!
            assertFalse(row.isEnabled)
            assertEquals(7, row.sortKey)
            assertEquals(7, dao.getMaxSortKey())
        } finally {
            db.close()
        }
    }

    @Test
    fun `setPinned creates a missing source stamped with the injected app version`() = runBlocking {
        val db = newDb()
        try {
            val dao = db.getSourcesDao()
            dao.setPinned("new-source", true, appVersionCode = 123)
            val row = dao.find("new-source")!!
            assertEquals(123, row.addedIn) // was BuildConfig.VERSION_CODE before the DAO moved out of :app
            assertTrue(row.isPinned)
        } finally {
            db.close()
        }
    }
}
